\set ON_ERROR_STOP on
\getenv runtime_password KRYLYA_RUNTIME_PASSWORD
BEGIN;
SELECT 'CREATE ROLE krylya_app LOGIN' WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'krylya_app') \gexec
ALTER ROLE krylya_app PASSWORD :'runtime_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO krylya_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO krylya_app;
REVOKE INSERT, UPDATE, DELETE ON "__EFMigrationsHistory" FROM krylya_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO krylya_app;
COMMIT;
